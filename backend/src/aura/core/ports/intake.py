"""Ports for the deal intake (phase 3): the intake store with its staged documents, and the
model adapter that fills one field group from retrieved passages."""
from datetime import datetime
from typing import Protocol, runtime_checkable

from aura.core.domain.document import Document
from aura.core.domain.intake import Intake, StagedChunk


@runtime_checkable
class IntakeRepository(Protocol):
    """Built for a viewer: a user sees and changes only the intakes they created (row-level
    security on deal_intake and on the staged documents); SYSTEM (the worker) sees all."""
    def add(self, intake: Intake) -> Intake: ...
    def get(self, intake_id: int, for_update: bool = False) -> Intake | None: ...
    def list_open(self) -> list[Intake]: ...
    def save(self, intake: Intake) -> Intake: ...
    def files(self, intake_id: int) -> list[Document]: ...
    def file_stages(self, intake_id: int) -> dict[int, str]:
        """document id -> index job status (queued | running | done | dead_letter)."""
        ...
    def add_file(self, document: Document) -> Document: ...
    def add_file_version(self, document_id: int, sha256: str, byte_size: int,
                         uploaded_by: str, uploaded_at: datetime) -> Document: ...
    def set_file_class(self, document_id: int, doc_class: str) -> None: ...
    def delete_file(self, intake_id: int, document_id: int) -> bool: ...
    def move_to_deal(self, intake_id: int, deal_id: int) -> list[Document]:
        """Re-point the intake's documents, their chunks, index jobs and model runs to the
        deal (nothing is parsed again); returns the moved documents."""
        ...
    def chunks(self, intake_id: int) -> list[StagedChunk]: ...
    def chunk(self, intake_id: int, chunk_id: int) -> StagedChunk | None: ...
    def page_text(self, document_id: int, page_from: int | None, page_to: int | None,
                  limit_chars: int = 12_000) -> str: ...
    def next_external_id(self) -> str: ...


@runtime_checkable
class FieldExtractor(Protocol):
    """The local model reading one field group. `fields` describes each field (key, label,
    description, type, format, options); `passages` is the screened, wrapped context with
    [C1]..[Cn] tags. Returns the parsed JSON object, or None when the answer was unusable.
    Raises a transient error (the run is retried) when the model cannot be reached."""
    model: str

    def extract(self, group: str, fields: list[dict], passages: str,
                transaction_class: str | None) -> dict | None: ...
