def _one_of(column: str, enum: type[Enum]) -> CheckConstraint:
    values = ", ".join(f"'{e.value}'" for e in enum)
    return CheckConstraint(f"{column} IN ({values})", name=f"ck_{column}_valid")


def _pk() -> Mapped[int]:
    """BIGINT GENERATED BY DEFAULT AS IDENTITY: integer keys as before (BY DEFAULT so the
    SQLite import can keep every row's id, then move the sequence past them)."""
    return mapped_column(BigInteger, Identity(), primary_key=True)


class InrAmount(TypeDecorator):
    """Rupee amounts: NUMERIC(20,2) in the database (exact, paise included), while Python
    keeps seeing what it stored: an int for a whole-rupee amount, a float otherwise."""
    impl = Numeric(20, 2)
    cache_ok = True

    def process_result_value(self, value, dialect):
        if value is None:
            return None
        value = Decimal(value)
        return int(value) if value == value.to_integral_value() else float(value)


# Statutory identifier formats as anchored POSIX regexes, so a malformed value cannot be
# stored whatever wrote it. `~` is case sensitive. Mirrors identifier_policy, which
# upper-cases before validating.
IDENTIFIER_FORMAT_CHECK = " OR ".join([
    "(scheme = 'PAN' AND value ~ '^[A-Z]{5}[0-9]{4}[A-Z]$')",
    "(scheme = 'DIN' AND value ~ '^[0-9]{8}$')",
    "(scheme = 'GSTIN' AND value ~ '^[0-9]{2}[A-Z]{5}[0-9]{4}[A-Z][0-9A-Z]{3}$')",
    "(scheme = 'CIN' AND value ~ '^[LU][0-9]{5}[A-Z]{2}[0-9]{4}[A-Z]{3}[0-9]{6}$')",
    "(scheme = 'LLPIN' AND value ~ '^[A-Z]{3}-[0-9]{4}$')",
])


